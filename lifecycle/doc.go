// Package lifecycle 是业务层 —— 用例编排，不拥有任何数据。
//
// # 契约
//
// 拥有：无。本包只有函数，没有状态；状态全在模型里，选择（启用清单、钩子）由壳传入。
// 提供三个用例：
//   - Initialize —— 配置打印 → 组件 → 插件 → 过滤器 → 服务，每步前后触发钩子
//   - Start      —— 插件（按依赖）→ 服务（等就绪）→ 后台内存释放
//   - Exit       —— 取消基础上下文 → 服务 → 过滤器 → 插件 → 组件
//
// 允许调用：core（契约）、plugin / service / component / daemon / freemem（模型 port）、
// filter（过滤器装配）、handler（钩子触发）。
// 禁止：拥有数据；把判定规则写在这里（「谁能启用」这类判定属于模型）。
//
// # 为什么钩子只在这里触发
//
// 钩子是编排事件，不是模型能力。模型内部自行触发会让生命周期顺序散落在各处，
// 谁也说不清一次 NewApp 到底跑了哪些回调。现在全部收敛在本包，顺序就是代码顺序。
//
// # 已知限制：一个进程只能有一个 app
//
// config 包的全局 Conf、handler 包的钩子表、filter 包的过滤器链、zapp 的 defaultApp
// 都是进程级单例，重复 NewApp 会重复注册命令行参数并 panic（flag redefined）。
// 这是采用 MSO 之前就存在的限制，本次重构未改变；若将来要多 app 并存，
// 这四处要一起改成实例化 + 组合根注入。
